const SETS = Object.fromEntries(Object.entries(MATRIX).map(([r, list]) => [r, new Set(list)]));

export const can = (user, permission) => Boolean(user && SETS[user.role]?.has(permission));
export const permissionsOf = (role) => [...(SETS[role] || [])].sort();
export const isRole = (role) => Object.hasOwn(ROLES, role);
